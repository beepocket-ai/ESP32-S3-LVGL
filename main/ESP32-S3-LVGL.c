/* ---------------- 底层绘图 ---------------- */
static void put_pixel(int x, int y, uint16_t color)
{
    if (x < 0 || y < 0 || x >= LCD_H_RES || y >= LCD_V_RES) {
        return;
    }
    fb[y * LCD_H_RES + x] = color;
}

static void fill_rect(int x, int y, int w, int h, uint16_t color)
{
    int x0 = x < 0 ? 0 : x;
    int y0 = y < 0 ? 0 : y;
    int x1 = x + w;
    int y1 = y + h;
    if (x1 > LCD_H_RES) {
        x1 = LCD_H_RES;
    }
    if (y1 > LCD_V_RES) {
        y1 = LCD_V_RES;
    }
    for (int yy = y0; yy < y1; yy++) {
        uint16_t *row = fb + yy * LCD_H_RES;
        for (int xx = x0; xx < x1; xx++) {
            row[xx] = color;
        }
    }
}

static void draw_hline(int x, int y, int w, uint16_t color)
{
    fill_rect(x, y, w, 1, color);
}

static void draw_vline(int x, int y, int h, uint16_t color)
{
    fill_rect(x, y, 1, h, color);
}

static void draw_frame(int x, int y, int w, int h, int t, uint16_t color)
{
    fill_rect(x, y, w, t, color);
    fill_rect(x, y + h - t, w, t, color);
    fill_rect(x, y, t, h, color);
    fill_rect(x + w - t, y, t, h, color);
}

static void draw_circle(int cx, int cy, int r, uint16_t color)
{
    int x = r;
    int y = 0;
    int err = 1 - r;
    while (x >= y) {
        put_pixel(cx + x, cy + y, color);
        put_pixel(cx + y, cy + x, color);
        put_pixel(cx - y, cy + x, color);
        put_pixel(cx - x, cy + y, color);
        put_pixel(cx - x, cy - y, color);
        put_pixel(cx - y, cy - x, color);
        put_pixel(cx + y, cy - x, color);
        put_pixel(cx + x, cy - y, color);
        y++;
        if (err < 0) {
            err += 2 * y + 1;
        } else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

static void draw_char(int x, int y, char c, int scale, uint16_t color)
{
    if (c < 32 || c > 126) {
        c = '?';
    }
    const uint8_t *glyph = font8x16[c - 32];
    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << col)) {
                fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

static int text_width(const char *s, int scale)
{
    int n = (int)strlen(s);
    return n > 0 ? n * 9 * scale - scale : 0;
}

static void draw_text(int x, int y, const char *s, int scale, uint16_t color)
{
    while (*s) {
        draw_char(x, y, *s, scale, color);
        x += 9 * scale;
        s++;
    }
}

static void draw_text_center(int cx, int y, const char *s, int scale, uint16_t color)
{
    draw_text(cx - text_width(s, scale) / 2, y, s, scale, color);
}

