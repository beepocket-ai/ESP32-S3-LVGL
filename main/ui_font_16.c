static bool font_get_glyph_dsc(const lv_font_t * font, lv_font_glyph_dsc_t * dsc,
                                  uint32_t letter, uint32_t letter_next)
{
    LV_UNUSED(font); LV_UNUSED(letter_next);
    int lo = 0, hi = (int)(sizeof(s_glyphs) / sizeof(s_glyphs[0])) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (s_glyphs[mid].cp == letter) {
            dsc->adv_w = s_glyphs[mid].adv;
            dsc->box_w = s_glyphs[mid].w;
            dsc->box_h = s_glyphs[mid].h;
            dsc->ofs_x = s_glyphs[mid].ofs_x;
            dsc->ofs_y = s_glyphs[mid].ofs_y;
            dsc->format = LV_FONT_GLYPH_FORMAT_A8;
            dsc->is_placeholder = false;
            dsc->gid.index = (uint32_t)mid;
            return true;
        }
        if (s_glyphs[mid].cp < letter) lo = mid + 1; else hi = mid - 1;
    }
    return false;
}

static const void * font_get_glyph_bitmap(lv_font_glyph_dsc_t * dsc, lv_draw_buf_t * draw_buf)
{
    const glyph_t * g = &s_glyphs[dsc->gid.index];
    if (g->w == 0 || g->h == 0) return NULL;
    uint32_t stride = draw_buf->header.stride;
    const uint8_t * src = s_bitmap + g->data_ofs;
    for (int y = 0; y < g->h; y++) {
        memcpy(draw_buf->data + y * stride, src + y * g->w, g->w);
    }
    return draw_buf;
}

